// 模様がえの確かめ（1.12.0）：天井の物を見上げて動かせる・小物を矢印で動かせる・一覧からえらべる。使い方：node tools/check/arrange.js
const http = require('http'), fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const mock = require('./mock.js');
const ROOT = path.resolve(__dirname, '..', '..'), OUT = path.join(__dirname, 'out');
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webmanifest': 'application/manifest+json' };
const serve = () => new Promise(res => { const srv = http.createServer((req, rsp) => { let f = decodeURIComponent(req.url.split('?')[0]); if (f.endsWith('/')) f += 'index.html'; const file = path.join(ROOT, f); if (!file.startsWith(ROOT) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { rsp.writeHead(404); return rsp.end(); } rsp.writeHead(200, { 'Content-Type': TYPES[path.extname(file)] || 'application/octet-stream' }); fs.createReadStream(file).pipe(rsp); }).listen(0, () => res(srv)); });
(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const srv = await serve(), base = `http://localhost:${srv.address().port}/`;
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: false }); await mock(ctx);
  const page = await ctx.newPage(), fails = [], errors = [];
  page.on('pageerror', e => errors.push(String(e))); page.on('dialog', d => d.accept());
  const check = (ok, msg) => { console.log((ok ? '  ○ ' : '  × ') + msg); if (!ok) fails.push(msg); };
  await page.addInitScript(() => { localStorage.setItem('studyroom.download', 'later'); localStorage.setItem('studyroom.notour', '1'); localStorage.setItem('studyroom.uinext', '0'); localStorage.setItem('studyroom.quality', 'low'); });
  await page.goto(base); await page.waitForSelector('.title-screen'); await page.click('.title-screen');
  await page.waitForSelector('button[type=submit]');
  if (!/登録/.test(await page.locator('button[type=submit]').textContent())) await page.click('.swap');
  await page.fill('input[name=name]', 'admin'); await page.fill('input[name=pw]', 'test1234'); await page.click('button[type=submit]');
  await page.waitForSelector('.mode-sheet [data-m=study]', { timeout: 60000 }); await page.click('.mode-sheet [data-m=study]');
  await page.waitForTimeout(2000); await page.evaluate(() => document.querySelector('.lb-screen .ok')?.click()); await page.waitForTimeout(600);
  await page.evaluate(() => { document.querySelector('.style-sheet .stylecard')?.click(); document.querySelector('.style-sheet .ok')?.click(); });
  await page.waitForTimeout(800);
  // 天井のライト・机・机の上の花瓶を置く
  await page.evaluate(async () => { const { itemById } = await import('/js/items.js'); for (const id of ['light-pendant-cone-black', 'table-plain-wood', 'decor-vase-white-round']) { window.__app.HS().inventory[id] = 1; await window.__app.putIntoRoom(itemById(id)); } window.__app.S.save(); });
  await page.waitForTimeout(2500);
  const pl = await page.evaluate(() => window.__app.curRoom().placed.map(p => ({ uid: p.uid, item: p.item, on: p.on })));
  const lamp = pl.find(p => p.item === 'light-pendant-cone-black'), vase = pl.find(p => p.item === 'decor-vase-white-round');
  check(lamp && vase, `置けた（${pl.map(p => p.item + (p.on != null ? '(上)' : '')).join(', ')}）`);
  check(vase && vase.on != null, '花瓶は机の上にのる');
  await page.evaluate(() => { window.__app.showHome(); window.__app.showEdit(); }); await page.waitForSelector('.editbar');
  console.log('1. 一覧からえらぶ');
  await page.click('.editbar .plist'); await page.waitForSelector('.pl-sheet');
  check(/天井/.test(await page.locator('.pl-sheet').textContent()) && /テーブル・棚の上/.test(await page.locator('.pl-sheet').textContent()), '一覧に「天井」「テーブル・棚の上」の分け方が出る');
  await page.screenshot({ path: path.join(OUT, 'arrange-list.png') });
  await page.click(`.pl-item[data-u="${lamp.uid}"]`); await page.waitForTimeout(2200);
  const sel = await page.evaluate(() => window.__app.room3d.selected);
  check(sel === lamp.uid, '一覧でえらぶと選んだ状態になる');
  const pitch = await page.evaluate(() => window.__app.room3d.pitch);
  check(pitch > 0.15, `天井のライトのほうを見上げる（${pitch.toFixed(2)}）`);
  console.log('2. 天井の物を、見上げたままなぞって動かす');
  const rect = await page.evaluate(() => { const r = window.__app.room3d, q = r.screenRect(r.objByUid[r.selected]); return q; });
  const p0 = await page.evaluate(() => { const p = window.__app.room3d.selectedPlacement(); return { x: p.x, z: p.z }; });
  const cx = (rect.x0 + rect.x1) / 2, cy = (rect.y0 + rect.y1) / 2;
  await page.mouse.move(cx, cy); await page.mouse.down();
  for (let k = 1; k <= 10; k++) { await page.mouse.move(cx + k * 8, cy); await page.waitForTimeout(30); }
  await page.mouse.up(); await page.waitForTimeout(400);
  const p1 = await page.evaluate(() => { const p = window.__app.room3d.selectedPlacement(); return { x: p.x, z: p.z }; });
  check(Math.hypot(p1.x - p0.x, p1.z - p0.z) > 0.1, `天井の物が動く（${p0.x.toFixed(2)},${p0.z.toFixed(2)} → ${p1.x.toFixed(2)},${p1.z.toFixed(2)}）`);
  await page.screenshot({ path: path.join(OUT, 'arrange-ceiling.png') });
  console.log('3. 小物を、矢印とまわりからつかんで動かす');
  await page.evaluate((u) => { window.__app.room3d.select(u); window.__app.room3d.focusSelected(); }, vase.uid); await page.waitForTimeout(2000);
  check(await page.locator('.nudge').count() === 1, '矢印のボタンが出る');
  const v0 = await page.evaluate(() => { const p = window.__app.room3d.selectedPlacement(); return { x: p.x, z: p.z, y: p.y, on: p.on }; });
  const b = await page.locator('.nudge [data-d="1,0"]').boundingBox();
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2); await page.mouse.down(); await page.waitForTimeout(700); await page.mouse.up(); await page.waitForTimeout(300);
  const v1 = await page.evaluate(() => { const p = window.__app.room3d.selectedPlacement(); return { x: p.x, z: p.z, y: p.y, on: p.on }; });
  const dist = Math.hypot(v1.x - v0.x, v1.z - v0.z);
  check(dist > 0.04, `押しつづけると動きつづける（${(dist * 100).toFixed(0)}cm）`);
  check(v1.on === v0.on && Math.abs((v1.y || 0) - (v0.y || 0)) < 0.01, '机の上にのったまま');
  for (let k = 0; k < 40; k++) await page.evaluate(() => window.__app.room3d.nudgeSelected(1, 0));
  const v2 = await page.evaluate(() => window.__app.room3d.selectedPlacement().on);
  check(v2 === v0.on, '机の外へは出ない（落ちない）');
  // まわり（物の外、指1本ぶん）からつかむ
  const r2 = await page.evaluate(() => { const r = window.__app.room3d; return r.screenRect(r.objByUid[r.selected]); });
  const near = await page.evaluate(([x, y]) => window.__app.room3d.nearSelected(x, y), [r2.x1 + 18, (r2.y0 + r2.y1) / 2]);
  check(near, '物のすぐ外を触っても、つかめる');
  await page.screenshot({ path: path.join(OUT, 'arrange-nudge.png') });
  check(!errors.length, `画面のエラーなし（${errors.join(' / ').slice(0, 160)}）`);
  await browser.close(); srv.close();
  console.log(fails.length ? `\nだめな所：${fails.length} 件` : '\nぜんぶ OK');
  process.exit(fails.length ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
