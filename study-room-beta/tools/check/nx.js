// 新しいデザインの確かめ（1.12.0 から標準）。登録→「さっそく1問」→つづき→答えた後→家具を買う→メニュー→設定→ガチャ→閉じ方。使い方：node tools/check/nx.js
const http = require('http'), fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const mock = require('./mock.js');
const ROOT = path.resolve(__dirname, '..', '..'), OUT = path.join(__dirname, 'out');
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webmanifest': 'application/manifest+json' };
const serve = () => new Promise(res => { const srv = http.createServer((req, rsp) => { let f = decodeURIComponent(req.url.split('?')[0]); if (f.endsWith('/')) f += 'index.html'; const file = path.join(ROOT, f); if (!file.startsWith(ROOT) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { rsp.writeHead(404); return rsp.end(); } rsp.writeHead(200, { 'Content-Type': TYPES[path.extname(file)] || 'application/octet-stream' }); fs.createReadStream(file).pipe(rsp); }).listen(0, () => res(srv)); });
(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const srv = await serve(), base = `http://localhost:${srv.address().port}/`;
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } }); await mock(ctx);
  const page = await ctx.newPage(), fails = [], errors = [];
  page.on('pageerror', e => errors.push(String(e))); page.on('dialog', d => d.accept());
  const check = (ok, msg) => { console.log((ok ? '  ○ ' : '  × ') + msg); if (!ok) fails.push(msg); };
  const vis = (q) => page.evaluate((q) => { const e = document.querySelector(q); return !!e && getComputedStyle(e).display !== 'none' && e.offsetParent !== null; }, q);
  await page.addInitScript(() => { localStorage.setItem('studyroom.download', 'later'); localStorage.setItem('studyroom.quality', 'low'); });
  console.log('1. 登録 → 目的 → 「さっそく1問」（ログボ・雰囲気・7枚の案内は出ない）');
  await page.goto(base); await page.waitForSelector('.title-screen'); await page.click('.title-screen'); await page.waitForSelector('button[type=submit]');
  if (!/登録/.test(await page.locator('button[type=submit]').textContent())) await page.click('.swap');
  await page.fill('input[name=name]', 'mio'); await page.fill('input[name=pw]', 'test1234'); await page.click('button[type=submit]');
  await page.waitForSelector('.mode-sheet [data-m=study]', { timeout: 60000 }); await page.click('.mode-sheet [data-m=study]');
  await page.waitForSelector('.nx-welcome', { timeout: 12000 }).catch(() => {});
  check(await page.locator('.nx-welcome').count() === 1, '「さっそく1問解く」の1枚が出る');
  check(await page.locator('.lb-screen, .style-sheet, .tour').count() === 0, 'ログボ・部屋の雰囲気・7枚の案内は出ない');
  await page.screenshot({ path: path.join(OUT, 'nx-1-welcome.png') });
  await page.click('.nx-welcome .go'); await page.waitForSelector('.subj-sheet', { timeout: 8000 });
  check(true, '「さっそく1問解く」で教科えらびが開く');
  console.log('2. 下のメニュー：4つ＋右端の「解く」、勉強｜パズルが見える');
  await page.evaluate(() => window.__app.showHome()); await page.waitForTimeout(500);
  const slots = await page.evaluate(() => [...document.querySelectorAll('.nx-bar .sl')].map(b => b.dataset.t).join(','));
  check(slots === 'room,furn,gacha,social', `下のボタンは いつも同じ4つ（${slots}）`);
  const ring = await page.locator('.nx-bar .solve-ring').boundingBox(), vw = 390;
  check(ring && ring.x + ring.width > vw - 30, `「解く」は右下の端（右から ${Math.round(vw - ring.x - ring.width)}px）`);
  check(await vis('.nx-bar .mode-toggle'), '「勉強｜パズル」の切りかえが部屋の画面に見える');
  await page.click('.nx-bar .mode-toggle [data-mode=puzzle]'); await page.waitForTimeout(500);
  check(await page.evaluate(() => window.__app.S.profile().mode) === 'puzzle', '「パズル」を押すと、すぐパズルになる');
  await page.click('.nx-bar .mode-toggle [data-mode=study]'); await page.waitForTimeout(500);
  await page.screenshot({ path: path.join(OUT, 'nx-2-home.png') });
  console.log('3. 解く → 答えた後（まちがい）の言い方');
  // 1.13.0：今日は数学を25分やったことにして、「同じ教科が続いている」の案内を出す
  await page.evaluate(async () => { const S = await import('/js/store.js'); S.logDay({}); const e = S.dayLog()[S.dayKey()]; e.t = { math: 25 * 60 }; e.u = { 'jp|古文単語': [3, 3] }; });
  await page.evaluate(() => document.querySelector('.solve-ring')?.click());
  await page.waitForFunction(() => { const b = document.querySelector('.subj[data-s=math]'); return b && !b.disabled; }, null, { timeout: 30000 });
  const recs = await page.locator('.subj-rec').count();
  check(recs >= 1 && recs <= 2, `教科えらびの「おすすめ」は2つまで（${recs}こ）`);
  await page.waitForTimeout(700); await page.screenshot({ path: path.join(OUT, 'nx-2b-subjects.png') });
  await page.click('.subj[data-s=math]'); await page.waitForTimeout(400);
  await page.evaluate(() => (document.querySelector('.sc-list [data-all]') || document.querySelector('.sc-list [data-gall]'))?.click()); await page.waitForSelector('.fcard');
  const ans = await page.evaluate(async () => { const t = document.querySelector('.choice .problem').textContent.trim(); const r = await fetch('/data/bank/math.json'); const a = await r.json(); const n = (x) => String(x).replace(/\s+/g, ''); return a.find(p => n(p.text) === n(t))?.answer; });
  await page.evaluate((ans) => { const c = [...document.querySelectorAll('.fcard')].find(b => +b.dataset.i !== ans); c.click(); }, ans);
  await page.waitForSelector('.nx-verdict', { timeout: 8000 });
  const verdict = (await page.locator('.nx-verdict').textContent()).trim();
  check(/ざんねん、まちがい/.test(verdict) && !/ちがいます/.test(verdict), `まちがいの言い方：「${verdict.replace(/\s+/g, ' ')}」`);
  check(await vis('.nx-next .more'), '「次の問題」が下にある');
  check(await page.locator('.gf-decay .gf-go').count() === 1, `同じ教科が続くと、ほかの教科をすすめる（${(await page.locator('.gf-decay').textContent().catch(() => '')).trim().slice(0, 60)}）`);
  await page.waitForTimeout(1200); await page.screenshot({ path: path.join(OUT, 'nx-3-result.png') });
  await page.click('.nx-next .home'); await page.waitForTimeout(900);
  await page.evaluate(() => document.querySelector('.solve-ring')?.click()); await page.waitForSelector('.nx-cta', { timeout: 8000 }).catch(() => {});
  check(await page.locator('.nx-cta').count() === 1, '次に「解く」を押すと「前回のつづき」が出る');
  await page.click('.nx-cta'); await page.waitForSelector('.fcard', { timeout: 8000 }).catch(() => {});
  check(await page.locator('.fcard').count() > 0, '「前回のつづき」から1タップで問題が始まる');
  await page.evaluate(() => document.querySelector('.quiz .back')?.click()); await page.waitForTimeout(800);
  console.log('4. 家具を買う（部屋の雰囲気はここで聞く）');
  await page.evaluate(() => { window.__app.HS().gauge = 9999; window.__app.S.save(); window.__app.showHome(); }); await page.waitForTimeout(500);
  await page.click('.nx-buy'); await page.waitForTimeout(600);
  check(await page.locator('.style-sheet').count() === 1, 'はじめて買う時に部屋の雰囲気を聞く');
  await page.evaluate(() => { document.querySelector('.style-sheet .stylecard')?.click(); document.querySelector('.style-sheet .ok')?.click(); });
  await page.waitForSelector('.nx-gtabs', { timeout: 8000 }).catch(() => {});
  check(await page.locator('.nx-gtabs button').count() >= 2, 'ジャンルは上のタブで切りかえ');
  check(/えらんで/.test(await page.locator('.cand-sheet .ok').textContent()), 'えらぶ前のボタンは「家具をえらんでください」');
  await page.click('.cand >> nth=0'); await page.waitForTimeout(400);
  check(/を(買う|もらう)/.test(await page.locator('.cand-sheet .ok').textContent()), `えらぶと「○○を買う」（${(await page.locator('.cand-sheet .ok').textContent()).trim()}）`);
  await page.click('.cand-sheet .ok'); await page.waitForTimeout(1500);
  // 1.15：買ったら、その場で置く場所を決める
  check(await page.locator('.editbar.place-new').count() === 1, '買うと「置く場所を決める」になる');
  check(await page.locator('.float-bar .rot, .float-bar .fb-name').count() >= 1 && await page.locator('.nudge').count() === 1, '買った家具が選ばれていて、回す・矢印が出る');
  const before = await page.evaluate(() => { const r = window.__app.curRoom(); const p = r.placed[r.placed.length - 1]; return JSON.stringify([p.x, p.z]); });
  await page.evaluate(() => document.querySelector('.nudge [data-d="1,0"]')?.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true })));
  await page.waitForTimeout(120);
  await page.evaluate(() => document.querySelector('.nudge [data-d="1,0"]')?.dispatchEvent(new PointerEvent('pointerup', { bubbles: true })));
  const after = await page.evaluate(() => { const r = window.__app.curRoom(); const p = r.placed[r.placed.length - 1]; return JSON.stringify([p.x, p.z]); });
  check(before !== after, `矢印で動かせる（${before} → ${after}）`);
  await page.screenshot({ path: path.join(OUT, 'nx-4b-place.png') });
  await page.click('.place-new .done'); await page.waitForTimeout(800);
  check(await page.locator('.cand-sheet').count() === 1, '「ここに置く」で、まだ買えるときは買う画面にもどる');
  await page.evaluate(() => { document.querySelector('.nx-buyx')?.click(); }); await page.waitForTimeout(500);
  // 1.15：模様がえで歩く
  await page.evaluate(() => window.__app.showEdit()); await page.waitForTimeout(500);
  check(await page.locator('.eb-view [data-v=walk]').count() === 1, '模様がえに「歩く」がある');
  await page.click('.eb-view [data-v=walk]'); await page.waitForTimeout(300);
  const cam0 = await page.evaluate(() => window.__app.room3d.camera.position.toArray().map(v => v.toFixed(2)).join(','));
  // 床のあたり（画面の下のほう）をタップ
  await page.mouse.click(195, 600); await page.waitForTimeout(150);
  await page.mouse.click(195, 600); await page.waitForTimeout(1800);
  const cam1 = await page.evaluate(() => window.__app.room3d.camera.position.toArray().map(v => v.toFixed(2)).join(','));
  check(cam0 !== cam1, `「歩く」で床をタップすると歩く（${cam0} → ${cam1}）`);
  await page.screenshot({ path: path.join(OUT, 'nx-4c-walk.png') });
  await page.click('.editbar .done'); await page.waitForTimeout(500);
  console.log('5. メニュー・設定・ガチャ・閉じ方');
  await page.evaluate(() => window.__app.showHome()); await page.waitForTimeout(400);
  await page.click('.nx-menubtn'); await page.waitForSelector('.nx-menu button'); await page.waitForTimeout(500);
  const items = await page.locator('.nx-menu .nm-t').allTextContents();
  check(items.includes('設定') && items.includes('勉強レポート') && items.includes('部屋の写真'), `右上のメニューを押すと、下に項目がのびる（${items.join('・')}）`);
  await page.screenshot({ path: path.join(OUT, 'nx-4-menu.png') });
  await page.mouse.click(120, 400); await page.waitForTimeout(400);
  check(await page.locator('.nx-menu').count() === 0, 'ほかの所を押すと、たたまれる');
  await page.click('.nx-menubtn'); await page.waitForSelector('.nx-menu button'); await page.waitForTimeout(400);
  await page.click('.nx-menu [data-k=settings]'); await page.waitForSelector('.nx-gh');
  await page.click('.screen .back'); await page.waitForTimeout(700);
  check(await page.locator('.home .nx-menu').count() === 1, '設定から「もどる」で、部屋（メニューがのびた状態）にもどる');
  await page.evaluate(() => document.querySelector('.nx-menu [data-k=settings]')?.click()); await page.waitForSelector('.nx-gh');
  check((await page.locator('.nx-gh').allTextContents()).join(',').startsWith('アカウント,画面と音,学習'), `設定は見出しつきのまとまり（${(await page.locator('.nx-gh').allTextContents()).join('・')}）`);
  await page.evaluate(() => window.__app.showHome()); await page.waitForTimeout(400);
  await page.evaluate(() => { const h = window.__app.HS(); h.rareTickets = 0; window.__app.S.save(); document.querySelector('.nx-bar [data-t=gacha]')?.click(); }); await page.waitForTimeout(800);
  check(await page.locator('.nx-howto').count() === 1, 'チケット0枚の時は「チケットの集め方」');
  await page.evaluate(() => window.__app.showHome()); await page.waitForTimeout(400);
  await page.evaluate(() => document.querySelector('.nx-bar [data-t=social]')?.click()); await page.waitForTimeout(500);
  check(await page.locator('.sheet .sh-x, .sheet .hs-close').count() >= 1, '下から出る画面は右上の ×');
  check(!errors.length, `画面のエラーなし（${errors.join(' / ').slice(0, 160)}）`);
  await browser.close(); srv.close();
  console.log(fails.length ? `\nだめな所：${fails.length} 件` : '\nぜんぶ OK');
  process.exit(fails.length ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
