// 期間限定イベントの確かめ（1.12.0）。使い方：node tools/check/event.js
const http = require('http'), fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const mock = require('./mock.js');
const ROOT = path.resolve(__dirname, '..', '..'), OUT = path.join(__dirname, 'out');
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webmanifest': 'application/manifest+json' };
const serve = () => new Promise(res => { const srv = http.createServer((req, rsp) => { let f = decodeURIComponent(req.url.split('?')[0]); if (f.endsWith('/')) f += 'index.html'; const file = path.join(ROOT, f); if (!file.startsWith(ROOT) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { rsp.writeHead(404); return rsp.end(); } rsp.writeHead(200, { 'Content-Type': TYPES[path.extname(file)] || 'application/octet-stream' }); fs.createReadStream(file).pipe(rsp); }).listen(0, () => res(srv)); });
(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const srv = await serve(), base = `http://localhost:${srv.address().port}/`;
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } }); await mock(ctx);
  const page = await ctx.newPage(), fails = [], errors = [];
  page.on('pageerror', e => errors.push(String(e))); page.on('dialog', d => d.accept());
  const check = (ok, msg) => { console.log((ok ? '  ○ ' : '  × ') + msg); if (!ok) fails.push(msg); };
  await page.addInitScript(() => { localStorage.setItem('studyroom.download', 'later'); localStorage.setItem('studyroom.notour', '1'); localStorage.setItem('studyroom.uinext', '0'); localStorage.setItem('studyroom.quality', 'low'); });
  await page.goto(base); await page.waitForSelector('.title-screen'); await page.click('.title-screen');
  await page.waitForSelector('button[type=submit]');
  if (!/登録/.test(await page.locator('button[type=submit]').textContent())) await page.click('.swap');
  await page.fill('input[name=name]', 'admin'); await page.fill('input[name=pw]', 'test1234'); await page.click('button[type=submit]');
  await page.waitForSelector('.mode-sheet [data-m=study]', { timeout: 60000 }); await page.click('.mode-sheet [data-m=study]');
  await page.waitForTimeout(2000); await page.evaluate(() => document.querySelector('.lb-screen .ok')?.click()); await page.waitForTimeout(600);
  await page.evaluate(() => { document.querySelector('.style-sheet .stylecard')?.click(); document.querySelector('.style-sheet .ok')?.click(); });
  await page.waitForTimeout(800);
  // テスト用のイベントを最後に入れて確かめる（しくみの確かめ。管理者の「ためす」は最後のイベント）
  await page.evaluate(async () => { const EV = await import('/js/events.js'); EV.EVENTS.push({ id: 'test-ev', name: 'テストフェス', unit: '雪の結晶', desc: 'テスト用', start: '2099-12-01', end: '2099-12-25', rewards: [{ at: 10, kind: 'ticket', amount: 2 }, { at: 30, kind: 'item', item: 'ev-gift-pile' }, { at: 60, kind: 'ticket4', amount: 1 }, { at: 100, kind: 'item', item: 'ev-snowman' }, { at: 150, kind: 'ticket', amount: 5 }, { at: 200, kind: 'item', item: 'ev-xmas-tree' }] }); });
  console.log('1. 期間の前は出ない → 管理者が「ためす」');
  check(await page.locator('.home .evbtn').count() === 0, '期間の前は部屋にイベントのボタンが出ない');
  await page.evaluate(() => document.querySelector('[data-t=menu]')?.click()); await page.waitForTimeout(400);
  await page.click('.menu-list [data-m=admin]'); await page.waitForSelector('.evpreview[data-ev=test-ev]');
  await page.click('.evpreview[data-ev=test-ev]'); await page.waitForTimeout(500);
  await page.evaluate(() => window.__app.showHome()); await page.waitForTimeout(600);
  check(await page.locator('.home .evbtn').count() === 1, '「ためす」で部屋にイベントのボタンが出る');
  console.log('2. 問題を解くと雪の結晶がたまる');
  await page.evaluate(() => document.querySelector('.solve-ring')?.click());
  await page.waitForFunction(() => { const b = document.querySelector('.subj[data-s=math]'); return b && !b.disabled; }, null, { timeout: 30000 });
  await page.click('.subj[data-s=math]'); await page.waitForTimeout(500);
  await page.evaluate(() => (document.querySelector('.sc-list [data-all]') || document.querySelector('.sc-list [data-gall]'))?.click()); await page.waitForSelector('.fcard');
  await page.click('.fcard >> nth=0'); await page.waitForSelector('.step .home', { timeout: 8000 });
  const pts1 = await page.evaluate(async () => { const EV = await import('/js/events.js'); return EV.stateOf(EV.activeEvent()).pts; });
  check(pts1 === 1 || pts1 === 2, `1問で ${pts1} ${'雪の結晶'}`);
  await page.click('.step .home'); await page.waitForTimeout(800);
  await page.evaluate(async () => { const EV = await import('/js/events.js'); EV.addPoints(118); window.__app.S.save(); window.__app.showHome(); });
  await page.waitForTimeout(500);
  const badge = await page.locator('.home .evbtn .gb-n').textContent().catch(() => '');
  check(badge === '4', `受け取れるごほうびの数が出る（${badge}）`);
  console.log('3. ごほうびを受け取る');
  await page.click('.home .evbtn'); await page.waitForSelector('.ev-sheet');
  await page.waitForTimeout(1500);
  await page.screenshot({ path: path.join(OUT, 'event-sheet.png') });
  check(await page.locator('.ev-claim').count() === 4, `「受け取る」が4つ（${await page.locator('.ev-claim').count()}）`);
  for (let k = 0; k < 4; k++) { await page.click('.ev-claim >> nth=0'); await page.waitForTimeout(300); }
  check(await page.locator('.ev-row.got').count() === 4 && await page.locator('.ev-claim').count() === 0, '受け取ると「受け取りずみ」になる');
  const gifts = await page.evaluate(() => window.__app.S.gifts().filter(g => g.from === 'event').map(g => g.itemId || g.kind));
  check(gifts.includes('ev-snowman') && gifts.includes('ev-gift-pile'), `プレゼントBOXに届く（${gifts.join(', ')}）`);
  await page.click('.ev-sheet .close'); await page.waitForTimeout(400);
  await page.click('.home .giftbox'); await page.waitForSelector('.gifts'); await page.click('.gb-all'); await page.waitForTimeout(600);
  const owned = await page.evaluate(() => ({ s: window.__app.HS().inventory['ev-snowman'] || 0, g: window.__app.HS().inventory['ev-gift-pile'] || 0 }));
  check(owned.s >= 1 && owned.g >= 1, `受け取ると持ち物に入る（雪だるま ${owned.s}・プレゼントの山 ${owned.g}）`);
  console.log('4. 部屋に置く');
  await page.evaluate(async () => { const { itemById } = await import('/js/items.js'); window.__app.showHome(); for (const id of ['ev-xmas-tree', 'ev-snowman', 'ev-gift-pile']) { window.__app.HS().inventory[id] = (window.__app.HS().inventory[id] || 0) + 1; await window.__app.putIntoRoom(itemById(id)); } });
  await page.waitForTimeout(3000);
  const placed = await page.evaluate(() => window.__app.curRoom().placed.map(p => p.item).filter(x => x.startsWith('ev-')));
  check(placed.length === 3, `3つとも部屋に置ける（${placed.join(', ')}）`);
  await page.evaluate(() => { const r = window.__app.room3d, it = r.items.children.find(o => /xmasTree/.test(o.children[0]?.name || '')); if (it) r.lookAt(it.position.clone().setY(1)); });
  await page.waitForTimeout(2500);
  await page.screenshot({ path: path.join(OUT, 'event-room.png') });
  console.log('5. 12月の「冬のカフェ」');
  const wc = await page.evaluate(async () => {
    const EV = await import('/js/events.js'); const { itemById } = await import('/js/items.js'); const G = await import('/js/gacha.js');
    const ev = EV.EVENTS.find(e => e.id === 'wintercafe2026');
    const items = ev.rewards.filter(r => r.kind === 'item').map(r => r.item);
    const ok = items.every(id => itemById(id) && G.gachaById(id)?.series === 'event' && G.gachaById(id).reward);
    const inGacha = [3, 4, 5].some(r => G.exchangeable(r).some(i => items.includes(i.id))) || items.some(id => JSON.stringify(G.oddsFor('standard')).includes(id));
    EV.setPreview(null); const before = EV.activeEvent('2026-11-30')?.id || null, during = EV.activeEvent('2026-12-10')?.id || null, after = EV.activeEvent('2026-12-29')?.id || null;
    EV.setPreview('wintercafe2026'); const st = EV.stateOf(ev); st.pts = 400; for (let i = 0; i < ev.rewards.length; i++) EV.claim(ev, i);
    window.__app.showHome(); await new Promise(r => setTimeout(r, 300));
    const P = await import('/js/profile.js');
    return { ok, inGacha, items: items.length, done: !!st.done, before, during, after, icon: !!document.querySelector('.home .evbtn'), titleShown: P.earnedTitles({ study: [], puzzle: [], evDone: ['wintercafe2026'] }).some(t => t.id === 'ev-wintercafe2026') };
  });
  check(wc.ok && wc.items === 7, `ごほうびの家具7つ（前の3つ＋新しい4つ）がそろっていて、イベントの家具になっている（${wc.items}）`);
  check(wc.before !== 'wintercafe2026' && wc.during === 'wintercafe2026' && wc.after !== 'wintercafe2026', `12/1〜12/28 だけ開く（${wc.before}・${wc.during}・${wc.after}）`);
  check(!wc.inGacha, 'イベントの家具はガチャ・かけら交換・確率表示に出ない');
  check(wc.done && wc.titleShown, `ぜんぶ受け取ると記念の称号（${JSON.stringify({ done: wc.done, t: wc.titleShown })}）`);
  check(wc.icon, 'ためし中は部屋にカフェのボタンが出る');
  console.log('6. 11月の「物理強化月間」');
  const ph = await page.evaluate(async () => {
    const EV = await import('/js/events.js'); const { itemById } = await import('/js/items.js'); const G = await import('/js/gacha.js');
    const ev = EV.EVENTS.find(e => e.id === 'physics2026');
    EV.setPreview(null);
    const dates = [EV.activeEvent('2026-11-09')?.id || null, EV.activeEvent('2026-11-10')?.id || null, EV.activeEvent('2026-11-30')?.id || null, EV.activeEvent('2026-12-01')?.id || null];
    const items = ev.rewards.filter(r => r.kind === 'item').map(r => r.item);
    const ok = items.every(id => itemById(id) && G.gachaById(id)?.reward);
    EV.setPreview('physics2026');
    const st = EV.stateOf(ev); st.pts = 0; st.bc = 0; st.bclaimed = 0; st.claimed = [];
    const a = EV.addAnswer({ sid: 'physics4', ok: true, repeat: false }).gained;
    const b = EV.addAnswer({ sid: 'physics', ok: false, repeat: false }).gained;
    const c = EV.addAnswer({ sid: 'math', ok: true, repeat: false }).gained;
    const d = EV.addAnswer({ sid: 'physics4', ok: true, repeat: true }).gained;
    for (let i = 0; i < 99; i++) EV.addAnswer({ sid: 'physics4', ok: true, repeat: false });
    const ready = EV.bonusReady(ev);
    const n0 = window.__app.S.gifts().length, got = EV.claimBonus(ev), gift = window.__app.S.gifts().slice(n0).map(g => g.kind + 'x' + g.amount).join();
    const again = EV.claimBonus(ev);
    window.__app.showHome(); await new Promise(r => setTimeout(r, 300));
    return { dates: dates.map(String).join(','), ok, items: items.length, pts: [a, b, c, d].join(','), bc: st.bc, ready, got, gift, again, left: EV.bonusLeft(ev) };
  });
  check(ph.dates === 'null,physics2026,physics2026,wintercafe2026', `11/10〜11/30 で、12/1 から冬のカフェ（${ph.dates}）`);
  check(ph.ok && ph.items === 3, `物理の家具3つがそろっている（${ph.items}）`);
  check(ph.pts === '3,1,1,0', `物理の正解3・まちがい1・ほかの教科1・同じ日のくり返し0（${ph.pts}）`);
  check(ph.bc === 100 && ph.ready === 2 && ph.got === 2 && ph.gift === 'ticketx2' && ph.again === 0, `物理の正解100問でレアチケット2枚・2回は受け取れない（${JSON.stringify(ph)}）`);
  check(ph.left === 50, `次のチケットまで あと50問（${ph.left}）`);
  await page.click('.home .evbtn'); await page.waitForSelector('.ev-sheet .ev-bonus'); await page.waitForTimeout(1200);
  await page.screenshot({ path: path.join(OUT, 'event-physics.png') });
  check(await page.locator('.ev-sheet .ev-bonus').count() === 1, 'イベントの画面に「50問ごとにレアチケット（物理の正解）」が出る');
  await page.evaluate(async () => { const EV = await import('/js/events.js'); EV.setPreview(null); });
  check(!errors.length, `画面のエラーなし（${errors.join(' / ').slice(0, 160)}）`);
  await browser.close(); srv.close();
  console.log(fails.length ? `\nだめな所：${fails.length} 件` : '\nぜんぶ OK');
  process.exit(fails.length ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
