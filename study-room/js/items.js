// 1行 = [id, 名前, 雰囲気の略(1〜2文字), src, 大きさ(最大辺 m), その他]
// その他：{ rare, special, place, surface, light(照明の色) }
function add(genre, def, rows) {
  for (const [id, name, st, src, size, o = {}] of rows) {
    const item = {
      id, name, genre,
      styles: [...st].map((c) => ST[c]),
      place: o.place || def.place,
      src, size,
      rare: !!o.rare,
    };
    const surface = o.surface || def.surface;
    if (surface) item.surface = surface;
    if (o.light) item.light = o.light;
    if (o.special) item.special = true;
    ITEMS.push(item);
  }
}

