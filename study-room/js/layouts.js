// その部屋で、この家具に合う場所（上から順に）
export function layoutSpots(roomId, item) {
  const L = LAYOUTS[roomId];
  if (!L) return [];
  const want = item.place === 'wall' ? 'wall' : item.place === 'ceiling' ? 'ceiling' : item.place === 'rug' ? 'rug' : 'floor';
  return L.filter(s => s.place === want && s.g.includes(item.genre)).map(({ place, g, ...pos }) => pos);
}
