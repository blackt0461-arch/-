// 関数電卓（1.14.0）の確かめ：物理（4択）で電卓を開く→問題の数字をタップ→計算→履歴→答えるととじる。使い方：node tools/check/calc.js
const http = require('http'), fs = require('fs'), path = require('path');
const { chromium } = require('playwright');
const mock = require('./mock.js');
const ROOT = path.resolve(__dirname, '..', '..'), OUT = path.join(__dirname, 'out');
const TYPES = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webmanifest': 'application/manifest+json' };
const serve = () => new Promise(res => { const srv = http.createServer((req, rsp) => { let f = decodeURIComponent(req.url.split('?')[0]); if (f.endsWith('/')) f += 'index.html'; const file = path.join(ROOT, f); if (!file.startsWith(ROOT) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { rsp.writeHead(404); return rsp.end(); } rsp.writeHead(200, { 'Content-Type': TYPES[path.extname(file)] || 'application/octet-stream' }); fs.createReadStream(file).pipe(rsp); }).listen(0, () => res(srv)); });
(async () => {
  fs.mkdirSync(OUT, { recursive: true });
  const srv = await serve(), base = `http://localhost:${srv.address().port}/`;
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 } }); await mock(ctx);
  const page = await ctx.newPage(), fails = [], errors = [];
  page.on('pageerror', e => errors.push(String(e))); page.on('dialog', d => d.accept());
  const check = (ok, msg) => { console.log((ok ? '  ○ ' : '  × ') + msg); if (!ok) fails.push(msg); };
  await page.addInitScript(() => { localStorage.setItem('studyroom.download', 'later'); localStorage.setItem('studyroom.quality', 'low'); });
  await page.goto(base); await page.waitForSelector('.title-screen'); await page.click('.title-screen'); await page.waitForSelector('button[type=submit]');
  if (!/登録/.test(await page.locator('button[type=submit]').textContent())) await page.click('.swap');
  await page.fill('input[name=name]', 'calcuser'); await page.fill('input[name=pw]', 'test1234'); await page.click('button[type=submit]');
  await page.waitForSelector('.mode-sheet [data-m=study]', { timeout: 60000 }); await page.click('.mode-sheet [data-m=study]');
  await page.waitForTimeout(1500);
  await page.evaluate(() => { document.querySelector('.nx-welcome')?.remove(); window.__app.showHome(); }); await page.waitForTimeout(500);
  console.log('1. 物理（4択）の問題に「電卓」がある');
  await page.evaluate(() => document.querySelector('.solve-ring')?.click());
  await page.waitForFunction(() => { const b = document.querySelector('.subj[data-s=physics4]'); return b && !b.disabled; }, null, { timeout: 30000 });
  await page.click('.subj[data-s=physics4]'); await page.waitForTimeout(400);
  await page.evaluate(() => (document.querySelector('.sc-list [data-all]') || document.querySelector('.sc-list [data-gall]'))?.click()); await page.waitForSelector('.fcard');
  // 数字の多い問題にさしかえる（9.8 をふくむ問題）
  await page.evaluate(async () => { const r = await fetch('/data/bank/physics4.json'); const a = await r.json(); const p = a.find(x => /9\.8/.test(x.text) && /5\.0|2\.0/.test(x.text)); const pr = document.querySelector('.problem'); pr.textContent = p.text; });
  check(await page.locator('.calc-btn').count() === 1, '問題の下に「電卓」ボタンがある');
  console.log('2. 開くと下半分に電卓、上に問題と選択肢が残る');
  await page.click('.calc-btn'); await page.waitForSelector('.calc .ck'); await page.waitForTimeout(300);
  const box = await page.evaluate(() => { const c = document.querySelector('.calc').getBoundingClientRect(); const q = document.querySelector('.problem').getBoundingClientRect(); return { calcTop: c.top, qBottom: q.bottom, h: innerHeight }; });
  check(box.calcTop > box.h * 0.38 && box.qBottom <= box.calcTop, `電卓は下半分、問題は上に見える（電卓の上端 ${Math.round(box.calcTop)}px・問題の下端 ${Math.round(box.qBottom)}px）`);
  const taps = await page.locator('.problem .num-tap').count();
  check(taps >= 2, `問題文の数字がタップできる（${taps}こ）`);
  console.log('3. 数字をタップ → × → 数字 → = で計算、履歴に残る');
  await page.locator('.problem .num-tap', { hasText: '9.8' }).first().click();
  await page.click('.ck[data-k="×"]'); await page.click('.ck[data-k="2"]'); await page.click('.ck[data-k="="]');
  const r1 = await page.evaluate(() => [document.querySelector('.calc-expr').textContent, document.querySelector('.calc-hist .ch b')?.textContent]);
  check(r1[0] === '19.6' && r1[1] === '19.6', `9.8×2 = ${r1[0]}（履歴 ${r1[1]}）`);
  await page.click('.ck[data-k="√"]'); await page.click('.ck[data-k="Ans"]'); await page.click('.ck[data-k=")"]');
  const prev = await page.locator('.calc-prev').textContent();
  check(/4\.427/.test(prev), `√(Ans) の途中の答えが見える（${prev}）`);
  await page.click('.ck[data-k="AC"]');
  await page.click('.ck[data-k="sin"]'); await page.click('.ck[data-k="3"]'); await page.click('.ck[data-k="0"]'); await page.click('.ck[data-k="="]');
  check(await page.locator('.calc-expr').textContent() === '0.5', 'sin(30) = 0.5（角度は度）');
  await page.click('.calc-hist .ch >> nth=0'); 
  check(await page.locator('.calc-expr').textContent() === '19.6', '履歴を押すと、その答えが入る');
  const vis4 = await page.evaluate(() => { const top = document.querySelector('.calc').getBoundingClientRect().top; return [...document.querySelectorAll('.fcard')].filter(b => b.getBoundingClientRect().bottom <= top + 1).length; });
  check(vis4 === 4, `電卓を開いても、選択肢が4つとも見える（${vis4}つ）`);
  await page.screenshot({ path: path.join(OUT, 'calc-1-open.png') });
  console.log('4. 答えると電卓はとじる');
  await page.click('.fcard >> nth=0'); await page.waitForTimeout(1200);
  check(await page.locator('.calc').count() === 0 && !(await page.evaluate(() => document.body.classList.contains('calc-on'))), '答えると電卓がとじる');
  console.log('4b. 段階に分けて解く（データがある問題だけ）');
  await page.evaluate(() => document.querySelector('.nx-next .more, .after .more')?.click()); await page.waitForSelector('.fcard');
  await page.evaluate(() => { const st = window.__app.sub(); const it = st.session.set[st.session.idx]; const p = window.__app.problemById(it.id);
    p.steps = [{ ask: 'テスト：1＋1 は？', choices: ['1', '2', '3', '4'], answer: 1, hint: '指で数えてみよう' }, { ask: 'では、答えはどれか。', choices: p.choices, answer: p.answer }];
    window.__app.runChoice(p, false); });
  await page.waitForSelector('.steps-btn');
  await page.click('.steps-btn'); await page.waitForSelector('.st-ask');
  check((await page.locator('.st-ask').textContent()).includes('1＋1'), '「段階に分けて解く」でステップ1が出る');
  await page.click('.fcard[data-i="0"]'); await page.waitForTimeout(200);
  check(await page.locator('.st-hint:not(.hide)').count() === 1, 'ステップでまちがえるとヒントが出る');
  await page.waitForTimeout(1200); await page.screenshot({ path: path.join(OUT, 'calc-2-steps.png') });
  await page.click('.fcard[data-i="1"]'); await page.waitForTimeout(700);
  check((await page.locator('.st-prog small').textContent()).includes('2 / 2'), '正解すると最後のステップへ');
  await page.click('.fcard >> nth=0'); await page.waitForSelector('.nx-verdict, .res', { timeout: 8000 });
  check(true, '最後のステップで答えると、ふつうの結果画面');
  console.log('5. 国語には電卓が出ない');
  await page.evaluate(() => document.querySelector('.nx-next .home, .after .home')?.click()); await page.waitForTimeout(800);
  await page.evaluate(() => document.querySelector('.solve-ring')?.click());
  await page.waitForFunction(() => { const b = document.querySelector('.subj[data-s=jp]'); return b && !b.disabled; }, null, { timeout: 30000 });
  await page.click('.subj[data-s=jp]'); await page.waitForTimeout(400);
  await page.evaluate(() => (document.querySelector('.sc-list [data-all]') || document.querySelector('.sc-list [data-gall]'))?.click()); await page.waitForSelector('.fcard');
  check(await page.locator('.calc-btn').count() === 0, '国語の問題には電卓ボタンがない');
  check(!errors.length, `画面のエラーなし（${errors.join(' / ').slice(0, 200)}）`);
  console.log(fails.length ? `\nだめな所：${fails.length} 件` : '\nぜんぶ OK');
  await browser.close(); srv.close(); process.exit(fails.length ? 1 : 0);
})();
